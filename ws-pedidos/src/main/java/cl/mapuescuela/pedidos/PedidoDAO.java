    public List<Comprobante> listarComprobantes(int pedidoId) throws SQLException {
        List<Comprobante> comprobantes = new ArrayList<>();

        String sql = "SELECT * FROM comprobante WHERE pedido_id = ? ORDER BY id DESC";

        try (PreparedStatement st = conn.prepareStatement(sql)) {
            st.setInt(1, pedidoId);

            try (ResultSet rs = st.executeQuery()) {
                while (rs.next()) {
                    Comprobante c = new Comprobante();
                    c.setId(rs.getInt("id"));
                    c.setPedidoId(rs.getInt("pedido_id"));
                    c.setArchivo(rs.getString("archivo"));
                    c.setTipo(rs.getString("tipo"));
                    c.setBytes(rs.getInt("bytes"));
                    c.setSubidoEn(rs.getObject("subido_en", LocalDateTime.class));
                    comprobantes.add(c);
                }
            }
        }
        return comprobantes;
    }

