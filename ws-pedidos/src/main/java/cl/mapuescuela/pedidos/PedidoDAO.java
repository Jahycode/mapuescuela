    public void crearTablas() throws SQLException {
        try (Statement st = conn.createStatement()) {

            st.execute("""
                CREATE TABLE IF NOT EXISTS producto (
                    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre    VARCHAR(120) NOT NULL,
                    categoria VARCHAR(20),
                    condicion VARCHAR(20),
                    medida    VARCHAR(60),
                    origen    VARCHAR(300),
                    marca_uso VARCHAR(300),
                    precio    INT NOT NULL,
                    stock     INT NOT NULL
                )
                """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS pedido (
                    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    cliente_nombre      VARCHAR(120),
                    cliente_email       VARCHAR(120) NOT NULL,
                    monto_total         INT,
                    modalidad_entrega   VARCHAR(20),
                    process_instance_id VARCHAR(64),
                    creado              TIMESTAMP,
                    desenlace           VARCHAR(30),
                    desenlace_motivo    VARCHAR(200),
                    desenlace_en        TIMESTAMP
                )
                """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS notificacion(
                    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pedido_id      INT NOT NULL REFERENCES pedido(id),
                    tipo           VARCHAR(40) NOT NULL,
                    destinatario   VARCHAR(120) NOT NULL,
                    mensaje        VARCHAR(300),
                    registrada_en  TIMESTAMP
                )
                """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS pedido_item (
                    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pedido_id   INT NOT NULL REFERENCES pedido(id),
                    producto_id INT NOT NULL REFERENCES producto(id),
                    precio      INT NOT NULL
                )
                """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS comprobante (
                    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pedido_id INT NOT NULL REFERENCES pedido(id),
                    archivo   VARCHAR(120) NOT NULL,
                    tipo      VARCHAR(60) NOT NULL,
                    bytes     INT NOT NULL,
                    subido_en TIMESTAMP NOT NULL
                )
                """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS revision (
                    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pedido_id   INT NOT NULL REFERENCES pedido(id),
                    revisor     VARCHAR(120) NOT NULL,
                    decision    VARCHAR(20) NOT NULL,
                    monto_leido INT,
                    mensaje     VARCHAR(500),
                    revisado_en TIMESTAMP NOT NULL
                )
                """);
                

            int cuantos;
            try (ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM producto")) {
                rs.next();
                cuantos = rs.getInt(1);
            }

            if (cuantos == 0) {
                cargarCatalogoInicial();
                System.out.println("Catálogo inicial cargado: " + CATALOGO_INICIAL.length + " objetos.");
            }
        }
    }

